const MARKER: &str = "<!-- Generated by ruleskill. Do not edit directly. -->";

#[test]
fn list_discovers_seeded_skills() {
    cmd()
        .arg("list")
        .assert()
        .success()
        .stdout(predicate::str::contains("github-actions"))
        .stdout(predicate::str::contains("rust"));
}

#[test]
fn validate_passes_for_seeded_skills() {
    cmd()
        .arg("validate")
        .assert()
        .success()
        .stdout(predicate::str::contains("validated 2 skill(s)"));
}

#[test]
fn validate_fails_for_missing_rule_file() {
    let catalog = minimal_catalog();
    write(
        catalog.path().join("rules/missing/skill.toml"),
        r#"
name = "missing"
title = "Missing"
description = "Missing file test."

[[rules]]
title = "Missing"
file = "missing.md"
when = "Always."
"#,
    );

    cmd()
        .env("RULESKILL_CATALOG_DIR", catalog.path())
        .arg("validate")
        .assert()
        .failure()
        .stderr(predicate::str::contains("referenced file does not exist"));
}

