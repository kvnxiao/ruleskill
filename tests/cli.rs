#[test]
fn auto_detection_installs_every_detected_harness() {
    let repo = TempDir::new().unwrap();
    fs::create_dir_all(repo.path().join(".agents")).unwrap();
    fs::create_dir_all(repo.path().join(".claude")).unwrap();

    cmd()
        .current_dir(repo.path())
        .args(["install", "github-actions"])
        .assert()
        .success();

    assert!(repo
        .path()
        .join(".agents/skills/github-actions/SKILL.md")
        .is_file());
    assert!(repo
        .path()
        .join(".claude/skills/github-actions/SKILL.md")
        .is_file());
}

